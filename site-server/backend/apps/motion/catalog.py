def styles() -> list[dict]:
    return STYLES


def get(style_id: str) -> dict | None:
    return next((s for s in STYLES if s["id"] == style_id), None)


def public_list() -> list[dict]:
    """لیستِ سبک‌ها برای گالریِ پنل (همهٔ پارامترها هم هست تا پیش‌نمایشِ زنده بسازد)."""
    return [dict(s, group_label=GROUPS.get(s["group"], s["group"])) for s in STYLES]


def export_json() -> dict:
    return {"styles": STYLES, "groups": GROUPS, "scene_types": list(SCENE_TYPES)}


def write_generated(path: str | Path) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(export_json(), ensure_ascii=False, indent=1, sort_keys=False) + "\n", encoding="utf-8")
    return p
