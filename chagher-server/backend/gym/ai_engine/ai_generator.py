class AllProvidersFailed(RuntimeError):
    """هیچ‌کدام از ارائه‌دهنده‌های زنجیره پاسخ ندادند."""

    def __init__(self, attempts):
        self.attempts = attempts
        detail = ' | '.join(f'{name}: {err}' for name, err in attempts) or 'بدون ارائه‌دهنده'
        super().__init__(f'هیچ ارائه‌دهنده هوش مصنوعی پاسخ نداد ({detail})')


class AIUsage:
    """مصرف توکن یک فراخوانی مدل — برای حساب‌کتاب هزینه در پنل ادمین.

    قیمت همان ارائه‌دهنده‌ای که واقعاً پاسخ داده همراه مصرف نگه داشته می‌شود.
    بدون این، اگر زنجیره به ارائه‌دهنده‌ی دوم می‌رفت، هزینه با تعرفه‌ی
    ارائه‌دهنده‌ی اول حساب می‌شد و حساب‌کتاب غلط درمی‌آمد.
    """

    __slots__ = ('model_name', 'input_tokens', 'output_tokens', 'provider_config')

    def __init__(self, model_name='', input_tokens=0, output_tokens=0,
                 provider_config=None):
        self.model_name = model_name
        self.input_tokens = int(input_tokens or 0)
        self.output_tokens = int(output_tokens or 0)
        self.provider_config = provider_config

    @classmethod
    def from_response(cls, response, model_name, provider_config=None):
        usage = getattr(response, 'usage', None)
        return cls(
            model_name=model_name,
            input_tokens=getattr(usage, 'prompt_tokens', 0) or 0,
            output_tokens=getattr(usage, 'completion_tokens', 0) or 0,
            provider_config=provider_config,
        )

    def __repr__(self):
        provider = (self.provider_config or {}).get('name', '-')
        return (
            f"AIUsage(provider={provider!r}, model={self.model_name!r}, "
            f"in={self.input_tokens}, out={self.output_tokens})"
        )


# مهلت برقراری اتصال، جدا از مهلت پاسخ. سروری که اصلاً بالا نیست باید در چند
# ثانیه رد شود تا زنجیره سریع سراغ بعدی برود؛ وگرنه کاربر به‌اندازه‌ی کل مهلت
# پاسخ (گاهی ۳۰۰ ثانیه) پشت یک سرور خاموش معطل می‌ماند.
CONNECT_TIMEOUT_SECONDS = 10


def build_client(config):
    """کلاینت سازگار با OpenAI برای یک ارائه‌دهنده.

    اولاما و اکثر سرورهای محلی همین پروتکل را ارائه می‌دهند، پس مسیر ابری و
    محلی از یک کلاینت استفاده می‌کنند و تنها تفاوتشان آدرس و کلید است.
    """
    api_key = config.get('api_key') or ''
    if not api_key:
        raise ValueError(
            f"ارائه‌دهنده «{config.get('name')}» کلید API ندارد. "
            'برای سرویس ابری کلید را وارد کنید یا نوع آن را «مدل محلی» بگذارید.'
        )
    answer_timeout = float(config.get('timeout_seconds') or 90)
    return OpenAI(
        base_url=config['base_url'],
        api_key=api_key,
        timeout=httpx.Timeout(
            answer_timeout,
            connect=min(CONNECT_TIMEOUT_SECONDS, answer_timeout),
        ),
        max_retries=0,  # تکرار را خودمان در سطح زنجیره مدیریت می‌کنیم
    )


# ---------------------------------------------------------------------------
# سازگاری پارامترها با خانواده‌های مختلف مدل
# ---------------------------------------------------------------------------
# مدل‌های استدلالی اوپن‌ای‌آی به‌جای `max_tokens` فقط `max_completion_tokens`
# را می‌پذیرند و `temperature` سفارشی را رد می‌کنند؛ بعضی درگاه‌ها هم
# `max_output_tokens` می‌خواهند. این تفاوت‌ها با آزمون‌وخطا کشف می‌شوند، اما
# نتیجه روی خود ارائه‌دهنده ذخیره می‌شود تا فقط یک بار هزینه بدهد.

# نام‌های شناخته‌شده‌ی پارامتر سقف توکن، به ترتیب اولویت پیشنهاد
TOKEN_PARAM_NAMES = ('max_completion_tokens', 'max_output_tokens', 'max_tokens')
TOKEN_PARAM_FALLBACK = 'max_completion_tokens'

# نشانه‌های متنی «این پارامتر پشتیبانی نمی‌شود» — فقط وقتی استفاده می‌شوند که
# سرور فیلد ساختاریافته‌ی `param` را نداده باشد.
_UNSUPPORTED_MARKERS = (
    'unsupported parameter', 'unsupported_parameter',
    'unsupported value', 'unsupported_value',
    'not supported', 'does not support', 'unknown parameter',
    'unrecognized', 'only the default', 'not permitted',
)

# تکرار خطاهای گذرا: یک بار، با مکثی کوتاه. یک تایم‌اوت لحظه‌ای نباید کل
# تولید برنامه را بسوزاند (به‌ویژه وقتی فقط یک ارائه‌دهنده تنظیم شده)، ولی
# تکرار بی‌پایان هم کاربر را پشت یک سرور مریض نگه می‌دارد.
TRANSIENT_RETRIES = 1
RETRY_SLEEP_SECONDS = 1.5

# سقف تلاش برای هر ارائه‌دهنده — محافظ در برابر حلقه‌ی بی‌پایان تطبیق
MAX_ATTEMPTS_PER_PROVIDER = 6

# مدل استدلالی ممکن است کل بودجه را صرف «فکر کردن» کند و هیچ متنی برنگرداند.
# در آن حالت یک بار با بودجه‌ی بزرگ‌تر دوباره می‌پرسیم.
TRUNCATED_BUDGET_FACTOR = 2
TRUNCATED_BUDGET_CAP = 30000


def _error_text(exc):
    return str(exc or '').lower()


def _rejected_param(exc):
    """نام پارامتری که سرور رد کرده — از خود پاسخ خطا، نه از روی متن پیام.

    کتابخانه‌ی OpenAI این مقدار را در `exc.param` می‌گذارد و درگاه‌های سازگار
    هم معمولاً در بدنه‌ی خطا می‌فرستند. تکیه بر متن پیام شکننده است، چون هر
    سرویس‌دهنده جمله‌ی خودش را می‌نویسد.
    """
    param = getattr(exc, 'param', None)
    if param:
        return str(param).strip()

    body = getattr(exc, 'body', None)
    if isinstance(body, dict):
        error = body.get('error')
        if isinstance(error, dict) and error.get('param'):
            return str(error['param']).strip()
        if body.get('param'):
            return str(body['param']).strip()
    return None


def _says_unsupported(exc, param_name):
    """آیا این خطا می‌گوید پارامتر `param_name` پشتیبانی نمی‌شود؟"""
    rejected = _rejected_param(exc)
    if rejected:
        return rejected == param_name

    text = _error_text(exc)
    if param_name not in text:
        return False
    return any(marker in text for marker in _UNSUPPORTED_MARKERS)


def _suggested_token_param(exc, current_param, already_tried):
    """نام جایگزینی که خود سرور پیشنهاد داده، وگرنه رایج‌ترین جایگزین."""
    text = _error_text(exc)
    for name in TOKEN_PARAM_NAMES:
        if name != current_param and name not in already_tried and name in text:
            return name
    if TOKEN_PARAM_FALLBACK not in already_tried:
        return TOKEN_PARAM_FALLBACK
    return None


def _is_transient(exc):
    """خطاهایی که تکرارشان منطقی است: تایم‌اوت، قطعی لحظه‌ای، شلوغی سرور."""
    if isinstance(exc, (APITimeoutError, APIConnectionError)):
        return True
    status = getattr(exc, 'status_code', None)
    if isinstance(status, int):
        return status in (408, 409, 425, 429) or status >= 500
    return False


def _response_text(response):
    choices = getattr(response, 'choices', None) or []
    if not choices:
        return ''
    return (getattr(choices[0].message, 'content', None) or '').strip()


def _finish_reason(response):
    choices = getattr(response, 'choices', None) or []
    if not choices:
        return None
    return getattr(choices[0], 'finish_reason', None)


def _complete_with_provider(client, provider, model, messages, max_tokens,
                            temperature, label, grow_on_empty=True):
    """یک درخواست کامل به یک ارائه‌دهنده، با تطبیق پارامتر و تکرار گذرا.

    سه چیز اینجا حل می‌شود که قبلاً به کاربر می‌رسید:

    ۱. **نام پارامتر سقف توکن** — مدل‌های استدلالی `max_tokens` را رد
       می‌کنند. نام درست یک بار کشف و روی ارائه‌دهنده ذخیره می‌شود، پس
       دفعات بعد بدون رفت‌وبرگشت اضافه ارسال می‌شود.
    ۲. **`temperature` سفارشی** — همان داستان؛ اگر مدل نپذیرد، حذف و
       ذخیره می‌شود.
    ۳. **خطای گذرا** — تایم‌اوت یا ۵xx یک بار تکرار می‌شود. بدون این، یک
       قطعی لحظه‌ای روی تنها ارائه‌دهنده، تولید برنامه را شکست می‌داد.

    اگر مدل کل بودجه را صرف استدلال کرده و متنی برنگردانده باشد
    (`finish_reason='length'` با محتوای خالی)، یک بار با بودجه‌ی بزرگ‌تر
    دوباره پرسیده می‌شود.
    """
    token_param = provider.effective_token_param()
    tried_token_params = {token_param}
    use_temperature = provider.supports_temperature is not False and temperature is not None

    budget = int(max_tokens)
    grew_budget = False
    transient_left = TRANSIENT_RETRIES
    learned = {}

    def flush_learning():
        if learned:
            provider.remember_param_style(**learned)
            learned.clear()

    for _attempt in range(MAX_ATTEMPTS_PER_PROVIDER):
        params = {'model': model, 'messages': messages, token_param: budget}
        if use_temperature:
            params['temperature'] = temperature

        try:
            response = client.chat.completions.create(**params)
        except Exception as exc:
            if _says_unsupported(exc, token_param):
                replacement = _suggested_token_param(exc, token_param, tried_token_params)
                if replacement:
                    logger.info(
                        'Provider %s / model %s rejected %s; switching to %s',
                        label, model, token_param, replacement,
                    )
                    token_param = replacement
                    tried_token_params.add(replacement)
                    learned['token_param'] = replacement
                    continue

            if use_temperature and _says_unsupported(exc, 'temperature'):
                logger.info(
                    'Provider %s / model %s rejected temperature=%s; '
                    'falling back to the model default',
                    label, model, temperature,
                )
                use_temperature = False
                learned['supports_temperature'] = False
                continue

            if _is_transient(exc) and transient_left > 0:
                transient_left -= 1
                logger.warning(
                    'Transient error from provider %s (%s: %s) — retrying once',
                    label, type(exc).__name__, exc,
                )
                time.sleep(RETRY_SLEEP_SECONDS)
                continue

            # چیزی که تا اینجا یاد گرفتیم نباید هدر برود، حتی اگر این
            # ارائه‌دهنده در نهایت شکست بخورد.
            flush_learning()
            raise

        flush_learning()

        if (
            grow_on_empty
            and not grew_budget
            and not _response_text(response)
            and _finish_reason(response) == 'length'
        ):
            bigger = min(budget * TRUNCATED_BUDGET_FACTOR, TRUNCATED_BUDGET_CAP)
            if bigger > budget:
                logger.warning(
                    'Provider %s / model %s used its whole budget without producing '
                    'text; retrying with %s=%s',
                    label, model, token_param, bigger,
                )
                budget = bigger
                grew_budget = True
                continue

        if _finish_reason(response) == 'length' and _response_text(response):
            logger.warning(
                'Provider %s / model %s hit the token ceiling; the program may be '
                'cut short (%s=%s)', label, model, token_param, budget,
            )

        return response

    raise RuntimeError('مدل پس از چند تلاش تطبیقی پاسخ نداد.')


def ping_model(provider):
    """یک درخواست کوچک واقعی به یک ارائه‌دهنده — برای تست اتصال در ادمین.

    عمداً از همان مسیر تولید برنامه می‌گذرد تا هم درستی آدرس/کلید/نام مدل
    سنجیده شود و هم پارامترهای قابل‌قبول همان‌جا کشف و ذخیره شوند؛ یعنی
    اولین کاربر واقعی دیگر هزینه‌ی کشف را نمی‌دهد.

    خروجی: نام مدلی که پاسخ داد.
    """
    client = build_client(provider.as_config())
    model = provider.resolve_model(client)
    _complete_with_provider(
        client, provider, model,
        messages=[{'role': 'user', 'content': 'ping'}],
        max_tokens=16,
        temperature=None,
        label=provider.name,
        grow_on_empty=False,   # پاسخ خالی برای ping مهم نیست
    )
    return model




class _ListenerResponse:
    """پاسخِ سرورِ شنونده را به شکلِ پاسخِ OpenAI درمی‌آورد.

    بقیهٔ کد (`response.choices[0].message.content` و `response.usage`) همان
    چیزی را می‌بیند که از سرویسِ ابری می‌دید، پس هیچ‌جای دیگری عوض نمی‌شود.
    """

    class _Msg:
        def __init__(self, content):
            self.content = content

    class _Choice:
        def __init__(self, content):
            self.message = _ListenerResponse._Msg(content)

    class _Usage:
        def __init__(self, usage):
            self.prompt_tokens = int((usage or {}).get('prompt_tokens') or 0)
            self.completion_tokens = int((usage or {}).get('completion_tokens') or 0)
            self.total_tokens = self.prompt_tokens + self.completion_tokens

    def __init__(self, text, usage=None):
        self.choices = [self._Choice(text)]
        self.usage = self._Usage(usage)


def call_model(messages, max_tokens, temperature=0.35):
    """فراخوانی مدل روی زنجیره‌ی اولویت.

    زنجیره به ترتیب اولویت پیمایش می‌شود و اولین ارائه‌دهنده‌ای که پاسخ
    بدهد استفاده می‌شود. سازگارکردن پارامترها با آن مدل، تکرار خطای گذرا و
    مدیریت بودجه‌ی توکن در `_complete_with_provider` انجام می‌شود؛ اینجا
    فقط تصمیم گرفته می‌شود که یک ارائه‌دهنده «پاسخ داد» یا باید سراغ بعدی
    رفت.

    خروجی: (response, provider_config)
    """
    providers = APIConfig.get_chain()
    if not providers:
        raise ValueError(
            'هیچ ارائه‌دهنده فعالی برای هوش مصنوعی تنظیم نشده است. '
            'در پنل ادمین حداقل یک مورد را فعال کنید.'
        )

    attempts = []

    for provider in providers:
        config = provider.as_config()
        label = f"#{provider.priority} {provider.name}"

        # ── حالتِ سوم: سرورِ شنونده ──
        # به او وصل نمی‌شویم؛ کار را در صف می‌گذاریم و او برمی‌دارد. اگر روشن
        # نباشد یا در مهلت جواب ندهد، همین‌جا استثنا می‌خورد و می‌رویم سرِ بعدی.
        if provider.provider_type == APIConfig.TYPE_LISTENER:
            try:
                from app.ai_bridge import run_via_listener
                text, usage = run_via_listener(provider, messages, max_tokens)
            except Exception as exc:
                provider.mark_failure(exc)
                attempts.append((label, '%s: %s' % (type(exc).__name__, exc)))
                logger.warning('شنوندهٔ %s نشد: %s', label, exc)
                continue
            provider.mark_success()
            config['model_name'] = provider.model_name or 'listener'
            return _ListenerResponse(text, usage), config

        try:
            client = build_client(config)

            # ارائه‌دهنده محلی ممکن است نام مدل نداشته باشد؛
            # در آن صورت فهرست مدل‌های خود سرور خوانده می‌شود.
            model = provider.resolve_model(client)
            config['model_name'] = model

            response = _complete_with_provider(
                client, provider, model, messages, max_tokens, temperature, label,
            )
        except Exception as exc:
            # هر خطای واقعی Provider باعث می‌شود سراغ Provider بعدی برویم.
            provider.mark_failure(exc)
            attempts.append(
                (label, f'{type(exc).__name__}: {exc}')
            )
            logger.warning(
                'AI provider failed, moving to next: %s — %s',
                label,
                exc,
            )
            continue

        if not _response_text(response):
            provider.mark_failure('خروجی خالی')
            attempts.append((label, 'خروجی خالی'))
            logger.warning(
                'AI provider returned empty output: %s',
                label,
            )
            continue

        provider.mark_success()

        if attempts:
            logger.info(
                'AI provider %s served after %d failed attempt(s)',
                label,
                len(attempts),
            )

        return response, config

    raise AllProvidersFailed(attempts)



