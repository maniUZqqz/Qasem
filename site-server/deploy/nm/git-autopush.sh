#!/usr/bin/env bash
# کدِ سرورِ سایت را با چیدمانِ دو پوشه‌ای به GitHub می‌فرستد:
#   site-server/        ⇐ /var/www/NM/upmarket (بک‌اند، پنل، سایتِ عمومی، اسکریپت‌های استقرار، کدِ موتورِ سه‌بعدی)
#   processing-server/  ⇐ /var/www/NM/upmarket/processing (بستهٔ سرورِ پردازش)
# مخزنِ کاری: /root/qasem-repo (جدا از پوشهٔ اجرا، تا چیدمانِ مخزن به اجرای سایت ربطی نداشته باشد).
# nm-git-autopush.timer هر ۶ ساعت اجرایش می‌کند؛ دستی:  bash deploy/nm/git-autopush.sh "پیام"
set -u
SRC=/var/www/NM/upmarket
REPO=/root/qasem-repo
REMOTE=https://github.com/maniUZqqz/Qasem.git
export GIT_TERMINAL_PROMPT=0
MSG="${1:-auto: $(date '+%Y-%m-%d %H:%M') from site server}"

if [ ! -d "$REPO/.git" ]; then
  mkdir -p "$REPO" && cd "$REPO" && git init -q -b main && git remote add origin "$REMOTE"
fi
cd "$REPO" || exit 1

EXCL=(--exclude='.git' --exclude='venv/' --exclude='node_modules/' --exclude='__pycache__/' --exclude='*.pyc' --exclude='*.log'
      --exclude='frontend/dist/' --exclude='website/.next/' --exclude='backend/staticfiles/' --exclude='backend/media/'
      --exclude='backend/.env' --exclude='backend/.env.local' --exclude='deploy/nm/ai.env' --exclude='website/.env.production.local'
      --exclude='website/.env.local' --exclude='data/' --exclude='logs/' --exclude='*.sqlite3' --exclude='up3d-engine/vendor/'
      --exclude='up3d-engine/data/' --exclude='processing/' --exclude='server-state/')
rsync -a --delete "${EXCL[@]}" "$SRC/" "$REPO/site-server/"
rsync -a --delete --exclude='work/' --exclude='logs/' --exclude='node.json' --exclude='vendor/' --exclude='__pycache__/' \
      "$SRC/processing/" "$REPO/processing-server/"

cat > "$REPO/README.md" <<'EOF'
# Qasem — NMarketing (UpMarket)

Two folders, two machines:

| Folder | Runs on | Contents |
|---|---|---|
| `site-server/` | the site server (static IP, e.g. 87.107.160.17:8040) | Django backend (`backend/`), React panel (`frontend/`), public website (`website/`, Next.js), 3D engine code (`up3d-engine/`), deploy scripts (`deploy/nm/`) |
| `processing-server/` | every GPU machine (no public IP needed) | `START.bat` + `agent.py`, ComfyUI profiles/graphs, 3D render worker, PersianAiKit editors |

## Site server

Copy `site-server/` to `/var/www/NM/upmarket/` and run `bash deploy/nm/install.sh` (idempotent: venv, `.env`,
migrations, admin user, builds, systemd services, nginx on port 8040). Secrets are not in git: `backend/.env`
(generated by install.sh), `deploy/nm/ai.env` (AI API key), `data/` (databases, tokens).
Manage with `deploy/nm/nm.sh status|restart|logs`. This repository is updated automatically from the server
every 6 hours (`deploy/nm/git-autopush.sh`).

## Processing server

Copy `processing-server/` to the GPU machine (Python 3.10+, ComfyUI running), run `START.bat`, paste the
enrollment key from the panel (Tools → Processing servers → "Register a new server"). The machine registers
itself under its own name. Details: `processing-server/README.md`.
EOF
cat > "$REPO/.gitignore" <<'EOF'
__pycache__/
*.pyc
*.log
*.sqlite3
node_modules/
.env
.env.local
.env.production.local
ai.env
node.json
EOF

git add -A >/dev/null 2>&1
if git diff --cached --quiet; then
  echo "nothing to commit"
else
  git -c user.name="NMarketing server" -c user.email="server@nmarketing.local" commit -q -m "$MSG" && echo "committed: $MSG"
fi
if git push -q -u origin main 2>/tmp/git-push.err; then
  echo "pushed to origin/main"
else
  echo "push failed: $(tail -n 2 /tmp/git-push.err)"; exit 1
fi
