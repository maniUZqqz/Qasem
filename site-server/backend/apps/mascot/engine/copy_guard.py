"""متنِ حباب و کپشنِ ماسکوت: نگهبانِ ادعا + جمله‌های پیشنهادیِ بی‌ادعا.

ماسکوت یک کارتونِ کشیده‌شده است؛ هرچه می‌گوید باید یا نوشتهٔ خودِ کاربر باشد یا از واقعیت‌های تأییدشدهٔ برند (docs/chagher/brand-facts-fa.md). این‌جا:
  * ``check_text`` قیمت، آمار، وعدهٔ نتیجه، نظرِ مشتری و ادعای پزشکی را در متنِ کاربر پیدا می‌کند (فارسی و انگلیسی). رندر بدونِ تأییدِ صریحِ کاربر انجام نمی‌شود.
  * ``suggested_lines`` فقط جمله‌های بی‌ادعا می‌دهد: چند جملهٔ عمومی + (برای فروشگاه‌هایی که واقعیت‌هایشان در مستندات هست) جمله‌های تأییدشده با منبعشان.
هیچ قیمت، آمار، نتیجه، نظرِ مشتری یا وعدهٔ پزشکی ساخته نمی‌شود.
"""
from __future__ import annotations

import re

_FA_DIGITS = str.maketrans("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩", "01234567890123456789")
_NUM = r"\d[\d.,٬]*"

#: (کد، عنوانِ فارسی، الگو)
_RULES: list[tuple[str, str, re.Pattern]] = [
    ("price", "قیمت یا مبلغ", re.compile(rf"(?:{_NUM}\s*(?:هزار|میلیون|میلیارد)?\s*(?:تومان|تومن|ریال|دلار|یورو)|(?:تومان|تومن|ریال)\b|[$€£]\s*{_NUM}|{_NUM}\s*(?:usd|irr|toman|dollars?|euros?)\b|"
                                                  rf"قیمت\s*(?:ویژه|مناسب|ارزان|پایین)|ارزان(?:‌|\s)?ترین|تخفیف\s*{_NUM}|{_NUM}\s*(?:٪|%|درصد)?\s*تخفیف|رایگان)", re.I)),
    ("statistic", "آمار یا درصد", re.compile(rf"(?:{_NUM}\s*(?:٪|%|درصد)|(?:بیش\s*از|بالای|حدود|نزدیک\s*به|\+)\s*{_NUM}\s*(?:نفر|مشتری|کاربر|مربی|برنامه|فروشگاه|ورزشکار|سفارش)|"
                                                       rf"{_NUM}\s*(?:نفر|مشتری|کاربر|مربی)\s*(?:از|تا|با)|رتبهٔ?\s*(?:اول|یک)|شمارهٔ?\s*(?:یک|۱|1)\b)", re.I)),
    ("result_claim", "وعدهٔ نتیجه", re.compile(r"(?:تضمین(?:ی)?|حتماً\s*(?:لاغر|نتیجه|عضله|چاق)|قطعاً|بدون\s*(?:شکست|خطا)|نتیجهٔ?\s*(?:قطعی|حتمی|تضمینی)|"
                                              rf"{_NUM}\s*کیلو|لاغر(?:ی)?\s*شو|چربی(?:‌|\s)?سوزی|guarantee[sd]?|results?\s*in\s*\d+)", re.I)),
    ("testimonial", "نظرِ مشتری", re.compile(r"(?:مشتری(?:‌های)?\s*(?:ما\s*)?(?:می‌گویند|میگویند|گفته|راضی)|نظرِ?\s*(?:مشتری|کاربر|کاربران)|رضایتِ?\s*(?:مشتری|مربیان|کاربران)|"
                                            r"تجربهٔ?\s*(?:مشتری|کاربران)|testimonial|customers?\s*(?:say|love))", re.I)),
    ("medical", "ادعای پزشکی", re.compile(r"(?:درمان|شفا|بیماری|دیابت|فشار\s*خون|سرطان|دارو|ترمیم\s*(?:درد|آسیب)|درد\s*را\s*(?:از\s*بین|برطرف)|جایگزینِ?\s*(?:پزشک|مربی|دکتر)|"
                                          r"treat(?:s|ment)?\b|cure[sd]?\b|diagnos\w+|medical)", re.I)),
    ("superlative", "ادعای «بهترین/اول»", re.compile(r"(?:بهترین|برترین|یگانه|بی‌رقیب|اولین\s*(?:و\s*)?(?:تنها|بهترین)|رقیب\s*ندارد|#\s*1|best\s*in)", re.I)),
]
BLOCKING = {"price", "statistic", "result_claim", "testimonial", "medical", "superlative"}


def check_text(text: str) -> list[dict]:
    """ادعاهای پرخطرِ یک متن. ⇒ [{code، label_fa، term}] (خالی = تمیز)."""
    t = str(text or "").translate(_FA_DIGITS)
    out, seen = [], set()
    for code, label, rx in _RULES:
        m = rx.search(t)
        if m and code not in seen:
            seen.add(code)
            out.append({"code": code, "label_fa": label, "term": m.group(0).strip()[:40]})
    return out


def message_fa(found: list[dict]) -> str:
    labels = "، ".join(f"«{f['label_fa']}»" for f in found)
    return (f"متن شاملِ {labels} است. شخصیتِ برند فقط چیزی را می‌گوید که خودتان تأیید کرده‌اید؛ قیمت، آمار، وعدهٔ نتیجه، نظرِ مشتری و ادعای پزشکی را بردارید، "
            "یا اگر منبعش را دارید «این ادعا را خودم تأیید کرده‌ام» را بزنید.")


# ------------------------------------------------------------------ جمله‌های پیشنهادی

#: جمله‌های عمومیِ بی‌ادعا (برای هر فروشگاه)
GENERIC_LINES = ("سلام!", "این را ببین", "نکتهٔ امروز", "یادت نره", "یک قدمِ کوچک، یک شروعِ خوب", "امتحانش کن", "سؤالی داری؟ بپرس", "بریم؟", "آماده‌ای؟", "قدمِ بعدی چیه؟")

#: واقعیت‌های تأییدشدهٔ برند؛ کلید = بخشی از نامِ فروشگاه. هر ردیف: (جمله، منبع). منبع: docs/chagher/brand-facts-fa.md
VERIFIED_LINES: dict[str, list[tuple[str, str]]] = {
    "چغر": [
        ("با چغر چغر تر شو", "brand-facts-fa.md §۱ (شعار)"),
        ("پیش‌نویسِ برنامه در کمتر از یک دقیقه", "brand-facts-fa.md §۲ و §۴"),
        ("دستیارِ هوش مصنوعیِ مربی‌ها", "brand-facts-fa.md §۱"),
        ("تصمیمِ نهایی با مربی است", "brand-facts-fa.md §۴ («پیش‌نویس را همیشه بگو»)"),
    ],
}


def suggested_lines(store_name: str = "") -> list[dict]:
    """[{text، source}]: اول جمله‌های تأییدشدهٔ برند (اگر هست)، بعد جمله‌های عمومی. همه از ``check_text`` تمیز درمی‌آیند."""
    name = (store_name or "").strip()
    out: list[dict] = []
    for key, rows in VERIFIED_LINES.items():
        if key and key in name:
            out += [{"text": t, "source": src} for t, src in rows]
    out += [{"text": t, "source": "generic"} for t in GENERIC_LINES]
    return [r for r in out if not check_text(r["text"])]
